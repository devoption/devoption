//! Deterministic Cargo artifacts from verified library plans; no publication/I/O.
use super::{MAX_PACKAGE_BYTES, source_tar, staging::StagedSource};
use crate::BuildPlan;
use devoption_registry::{HostedRegistry, Sha256};
use flate2::{Compression, GzBuilder};
use serde_json::json;
use std::{
    collections::BTreeMap,
    io::{self, Write},
};

const PUBLIC_INDEX: &str = "https://github.com/rust-lang/crates.io-index";
pub const MAX_INDEX_LINE_BYTES: usize = 256 * 1024;

/// Owned archive/index bytes bound to source-stage provenance. This neither
/// attests build success nor authorizes publication, serving or execution.
/// No Debug implementation exposes private metadata, code or registry endpoints.
#[derive(Clone, PartialEq, Eq)]
pub struct CargoPackage {
    source: StagedSource,
    archive: Vec<u8>,
    sha256: Sha256,
    index_path: String,
    index_line: Vec<u8>,
}
impl CargoPackage {
    pub fn from_plan(destination: HostedRegistry, plan: &BuildPlan) -> io::Result<Self> {
        let staged = StagedSource::from_plan(destination.clone(), plan).map_err(|_| invalid())?;
        let source = &plan.details().source;
        if source.files().iter().any(|file| {
            [
                "Cargo.toml.orig",
                ".cargo_vcs_info.json",
                ".cargo-checksum.json",
            ]
            .iter()
            .any(|reserved| {
                file.path()
                    .split('/')
                    .next()
                    .is_some_and(|part| part.eq_ignore_ascii_case(reserved))
            })
        }) {
            return Err(invalid());
        }
        let original = source
            .files()
            .iter()
            .find(|file| file.path() == "Cargo.toml")
            .ok_or_else(invalid)?
            .bytes();
        let manifest: toml::Table =
            toml::from_str(std::str::from_utf8(original).map_err(|_| invalid())?)
                .map_err(|_| invalid())?;
        let edition = manifest["package"]["edition"]
            .as_str()
            .ok_or_else(invalid)?;
        // All interpolated source values are already constrained by source admission;
        // quote through JSON for canonical ASCII TOML string escaping.
        let quote = |value: &str| serde_json::to_string(value).map_err(|_| invalid());
        let mut normalized = format!(
            "# Generated by DevOption; original bytes are in Cargo.toml.orig.\n[package]\nname={}\nversion={}\nedition={}\nbuild=false\nautobins=false\nautoexamples=false\nautotests=false\nautobenches=false\n[lib]\nname={}\npath=\"src/lib.rs\"\ncrate-type=[\"rlib\"]\n",
            quote(source.package())?,
            quote(source.version())?,
            quote(edition)?,
            quote(&source.package().replace('-', "_"))?
        );
        let mut dependencies = Vec::new();
        if let Some(entries) = manifest.get("dependencies").and_then(toml::Value::as_table) {
            // Explicit sort independent of TOML map backend/configuration.
            let ordered: BTreeMap<_, _> = entries.iter().collect();
            for (name, value) in ordered {
                let (version, defaults, index) = if let Some(pin) = value.as_str() {
                    (pin, true, PUBLIC_INDEX)
                } else {
                    let fields = value.as_table().ok_or_else(invalid)?;
                    let pin = fields
                        .get("version")
                        .and_then(toml::Value::as_str)
                        .ok_or_else(invalid)?;
                    let index =
                        if let Some(alias) = fields.get("registry").and_then(toml::Value::as_str) {
                            source
                                .request()
                                .hosted_registries()
                                .bindings()
                                .iter()
                                .find(|binding| binding.id().as_str() == alias)
                                .ok_or_else(invalid)?
                                .index()
                        } else {
                            PUBLIC_INDEX
                        };
                    (
                        pin,
                        fields
                            .get("default-features")
                            .and_then(toml::Value::as_bool)
                            .unwrap_or(true),
                        index,
                    )
                };
                normalized += &format!(
                    "[dependencies.{}]\nversion={}\ndefault-features={}\nregistry-index={}\n",
                    quote(name)?,
                    quote(version)?,
                    defaults,
                    quote(index)?
                );
                dependencies.push(json!({"name":name,"req":version,"features":[],"optional":false,"default_features":defaults,"target":null,"kind":"normal","registry":if index == destination.index() { None } else { Some(index) }}));
            }
        }
        let mut files: BTreeMap<&str, &[u8]> = source
            .files()
            .iter()
            .map(|file| (file.path(), file.bytes()))
            .collect();
        files.insert("Cargo.toml.orig", original);
        files.insert("Cargo.toml", normalized.as_bytes());
        let tar = source_tar(source.package(), source.version(), files)?;
        let mut encoder = GzBuilder::new()
            .mtime(0)
            .operating_system(255)
            .write(Vec::new(), Compression::new(6));
        encoder.write_all(&tar).map_err(|_| invalid())?;
        let archive = encoder.finish().map_err(|_| invalid())?;
        if archive.len() > MAX_PACKAGE_BYTES {
            return Err(invalid());
        }
        let sha256 = Sha256::digest(&archive);
        let checksum: String = sha256.bytes().iter().map(|b| format!("{b:02x}")).collect();
        let mut index_line = serde_json::to_vec(&json!({"name":source.package(),"vers":source.version(),"deps":dependencies,"cksum":checksum,"features":{},"yanked":false})).map_err(|_| invalid())?;
        index_line.push(b'\n');
        if index_line.len() > MAX_INDEX_LINE_BYTES {
            return Err(invalid());
        }
        let name = source.package().to_ascii_lowercase();
        let index_path = match name.len() {
            1 => format!("1/{name}"),
            2 => format!("2/{name}"),
            3 => format!("3/{}/{name}", &name[..1]),
            _ => format!("{}/{}/{name}", &name[..2], &name[2..4]),
        };
        Ok(Self {
            source: staged,
            archive,
            sha256,
            index_path,
            index_line,
        })
    }
    pub fn source(&self) -> &StagedSource {
        &self.source
    }
    pub fn archive(&self) -> &[u8] {
        &self.archive
    }
    pub fn archive_sha256(&self) -> Sha256 {
        self.sha256
    }
    pub fn index_path(&self) -> &str {
        &self.index_path
    }
    pub fn index_line(&self) -> &[u8] {
        &self.index_line
    }
}
fn invalid() -> io::Error {
    io::Error::other("unsupported or oversized Cargo source package")
}

